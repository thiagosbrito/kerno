import type { AuditOutcome, OrgRole } from "@kerno/contracts";

/** Result of verifying the caller's session with the auth server (not just decoding a cookie). */
export type SessionResult =
  | { readonly status: "authenticated"; readonly userId: string }
  | { readonly status: "unauthenticated" }
  | { readonly status: "unavailable" };

export type RoleLookup =
  | { readonly status: "member"; readonly role: OrgRole }
  | { readonly status: "not_member" }
  | { readonly status: "unavailable" };

export type MutationResult = "ok" | "not_found" | "forbidden" | "conflict" | "unavailable";

/**
 * Membership access through the CALLER's own credentials, so RLS applies on top of every check
 * the server makes. Roles are read from the current `memberships` row on every call: never from
 * the token, a cookie or a cache, which is what makes revocation take effect immediately.
 */
export interface MemberStore {
  getRole(organizationId: string, userId: string): Promise<RoleLookup>;
  changeRole(organizationId: string, userId: string, role: OrgRole): Promise<MutationResult>;
  remove(organizationId: string, userId: string): Promise<MutationResult>;
}

export interface DeniedAudit {
  readonly organizationId: string;
  readonly actorUserId: string;
  readonly action: string;
  readonly targetType: string;
  readonly targetId: string;
  readonly outcome: AuditOutcome;
  readonly correlationId: string;
  readonly details: Readonly<Record<string, string>>;
}

/** Records application-level events. Row changes are audited by database triggers instead. */
export interface AuditSink {
  record(event: DeniedAudit): Promise<void>;
}

export interface LogEntry {
  readonly event: string;
  readonly correlationId: string;
  readonly outcome: "allowed" | "denied" | "error";
  readonly reason: string;
}

/** Per-request dependencies: built fresh for every request so no identity is shared between requests. */
export interface AuthDependencies {
  readonly allowedOrigins: ReadonlySet<string>;
  getSession(): Promise<SessionResult>;
  readonly members: MemberStore;
  readonly audit: AuditSink;
  /** Redacted structured log line: ids and reasons only, never tokens, emails or bodies. */
  log(entry: LogEntry): void;
  /** Generated by the server for this request (never taken from the client); also forwarded to the database. */
  readonly correlationId: string;
}
